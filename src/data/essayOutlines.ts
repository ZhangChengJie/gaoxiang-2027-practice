export type EssayOutline = {
  essayId: string
  prompt: string[]
  referenceOutline: string[]
  checklist: { id: string; text: string }[]
}
export const OUTLINE_MINUTES = 15

const commonChecks = [
  '摘要含项目背景、本人角色、围绕论题的管理动作和成果',
  '背景交代目标、范围、规模、周期及本人职责，数字口径一致',
  '逐一回应子问题（1）（2）（3），主体小节与子问题对应',
  '每个主体要点有具体情境、本人动作和量化结果',
  '工具或术语使用准确，说明为什么选择及如何应用',
  '说明与其他管理领域或绩效域的协同及交付价值',
  '结尾写真实不足、原因及可执行的改进措施',
  '提纲分配摘要、背景、主体和结尾篇幅，避免技术细节挤占管理论述',
]
function outline(
  essayId: string, title: string, subquestions: [string, string, string],
  body: [string, string, string], focus: string, improvement: string,
): EssayOutline {
  return {
    essayId,
    prompt: [
      title,
      '请结合你参与管理的信息系统项目，围绕上述论题展开论述。说明项目背景及本人承担的工作，并回答以下问题。',
      ...subquestions.map((text, i) => `（${i + 1}）${text}`),
    ],
    referenceOutline: [
      `摘要要点：概括项目背景、项目经理职责，以及围绕“${title.replace(/^论/, '')}”的三项核心管理动作，点明与目标一致的成果，约 300 字。`,
      '背景：可围绕市级综合服务平台组织材料，范围含 24 个部门的申请、审批及运营移交，预算 1200 万元、周期 14 个月、团队 32 人；本人负责整合、跨部门协调及交付。交代业务痛点、目标和论题约束。此处背景和下列指标供组织提纲，正式写作须替换为本人真实项目经历并保持统计口径一致。',
      ...body.map((text, i) => `主体（${i + 1}）：${text}`),
      `结尾：总结三项实践对交付与业务价值的贡献，避免重新抄写定义。写清不足与改进：${improvement}。全文按 2500—3500 字组织，主体逐题回应，提纲标注关键案例、数字依据与段落篇幅。`,
    ],
    checklist: [...commonChecks, focus].map((text, i) => ({ id: `${essayId}-check-${i + 1}`, text })),
  }
}

