export type ScoringPoint = { id: string; text: string; score: number }
export type CaseQuestion = { id: string; prompt: string; score: number; scoringPoints: ScoringPoint[]; reference: string }
export type CasePractice = {
  id: string
  title: string
  kind: 'calc' | 'fault' | 'theory' | 'mixed'
  domains: string[]
  minutes: number
  background: string[]
  questions: CaseQuestion[]
}

// IDs are persistent progress keys. Keep question and scoring-point order stable.
function question(id: string, prompt: string, score: number, points: [number, string][]): CaseQuestion {
  return {
    id, prompt, score,
    scoringPoints: points.map(([value, text], i) => ({ id: `${id}-p${i + 1}`, text, score: value })),
    reference: points.map(([, text], i) => `${i + 1}. ${text}`).join('\n'),
  }
}

