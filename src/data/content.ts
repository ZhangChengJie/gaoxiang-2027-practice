const perfTerms = perfFacets.map(([term]) => term)
export const performanceQuestions: Question[] = perfFacets.flatMap(([term, items], i) =>
  items.map(([text, explanation], j) => {
    const choices = [term, ...perfTerms.filter((x) => x !== term).slice(j, j + 3)]
    const answer = (i + j) % 4
    const opts = [...choices]
    ;[opts[0], opts[answer]] = [opts[answer], opts[0]]
    return {
      id: `pd-${i}-${j}`,
      chapter: 'performance',
      domain: 'performance',
      topic: '绩效域辨析',
      text,
      options: opts,
      answer,
      explanation,
    }
  }),
)

export const allQuestions: Question[] = [...chapters.flatMap((c) => c.questions), ...performanceQuestions]

export const questionsByDomain: Record<string, Question[]> = Object.fromEntries(
  DOMAINS.map(({ key }) => [key, allQuestions.filter((question) => question.domain === key)]),
)
